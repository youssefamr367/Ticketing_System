import "dotenv/config";
import { z } from "zod";

const envSchema = z.object({
  PORT: z.coerce.number().int().positive().default(3000),
  NODE_ENV: z
    .enum(["development", "production", "test"])
    .default("development"),
});

const parsed = envSchema.parse(process.env);

export const env = {
  PORT: parsed.PORT,
  NODE_ENV: parsed.NODE_ENV,
};
